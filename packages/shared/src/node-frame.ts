/**
 * Check a contract before it is allowed to register.
 *
 * This runs at boot, not in a test, deliberately: a connector that cannot be
 * trusted should stop the deploy rather than wait to be discovered by a
 * customer whose agent quietly did nothing.
 */
export function validateNodeFrame(contract: NodeFrame): string[] {
  const problems: string[] = [];
  const id = contract.id || "(unnamed connector)";

  if (!/^[a-z0-9]+\.[a-z0-9_]+$/.test(contract.id ?? "")) {
    problems.push(`${id}: the id must look like "apollo.find_people".`);
  }
  if (!/^\d+\.\d+\.\d+$/.test(contract.version ?? "")) {
    problems.push(`${id}: version must be like "1.0.0" so a rollout can be staged.`);
  }
  if (!contract.provider?.apiVersion) {
    problems.push(`${id}: name the provider's API version, or nobody can tell what a deprecation affects.`);
  }
  if (!contract.provider?.docsUrl) {
    problems.push(`${id}: link the provider's docs — it is the first thing a maintainer opens.`);
  }
  // A card is one line of about twelve characters. A label longer than this
  // truncates, and the truncated part is usually the provider's name — the one
  // word that tells an architect what they are looking at.
  const cardLabel = contract.shortLabel ?? contract.label ?? "";
  if (cardLabel.length > 18) {
    problems.push(
      `${id}: "${cardLabel}" is too long for the sidebar card and will be cut off. Set shortLabel to the company's name — "Apollo", "Instantly".`
    );
  }
  if (!contract.produces?.length) {
    problems.push(`${id}: declare what it produces, or the engine cannot tell success from silence.`);
  }
  if (!contract.produces?.some((output) => output.required)) {
    problems.push(
      `${id}: at least one output must be required. With none, "it worked" and "it did nothing" are the same answer.`
    );
  }
  if (typeof contract.heart !== "function") {
    problems.push(`${id}: no heart — the one piece of code a connector must have.`);
  }
  /*
   * A probe that IS the heart.
   *
   * A fresh writer, given only this file, wrote `probe: heart` — which reads
   * like reuse and is a daily false alarm: the probe runs with no business
   * config, so the heart builds a URL out of undefined, gets a 404, and the
   * connector reports itself broken every morning until somebody stops reading
   * the alerts. A probe is a tiny call that needs nothing but the credential.
   */
  if (contract.probe && contract.probe === contract.heart) {
    problems.push(
      `${id}: the self-test is the same function as the heart. A probe runs with no business config, so it must be its own small call that needs only the credential.`
    );
  }

  /*
   * A heart that reaches the network itself.
   *
   * Everything the engine needs in order to do its job — the status that
   * decides whether a retry is sensible, the timeout, the rehearsal guard — is
   * in the client it hands you. A heart calling `fetch` looks correct,
   * typechecks, passes every other check here, and then retries a wrong API
   * key on every run because the status was left in a string.
   */
  if (typeof contract.heart === "function" && /\bfetch\s*\(/.test(contract.heart.toString())) {
    problems.push(
      `${id}: the heart calls fetch() directly. Use context.http — it carries the status the engine needs to decide whether retrying is sensible.`
    );
  }

  if (!/^\d{4}-\d{2}-\d{2}$/.test(contract.provider?.lastVerified ?? "")) {
    problems.push(`${id}: lastVerified must be a plain date like "2026-08-20" — it is what tells a maintainer how stale this is.`);
  }

  if (contract.execution === "paged" && !contract.limits?.pageSize) {
    problems.push(`${id}: paged work needs a page size, or it will ask for everything at once.`);
  }
  // An inbound connector with no way to read a knock is a dead address: the
  // business pastes it into their provider, the provider delivers, and nothing
  // happens for ever.
  if (contract.execution === "inbound") {
    if (typeof contract.receive !== "function") {
      problems.push(`${id}: it is inbound but has no receive() — nothing would ever read what the provider sends.`);
    }
    if (!contract.inbound?.instructions) {
      problems.push(`${id}: it is inbound but does not say what a business should do with the address we give them.`);
    }
  }
  if (contract.execution !== "inbound" && typeof contract.receive === "function") {
    problems.push(`${id}: it has a receive() but is not declared inbound, so it would never be called.`);
  }
  if (contract.execution === "paged" && !contract.limits?.maxPages) {
    problems.push(`${id}: paged work needs a page ceiling, or a runaway list can spend without end.`);
  }
  if ((contract.limits?.callsPerDay ?? 0) <= 0) {
    problems.push(`${id}: a daily call limit is required. "Unlimited" is how a bill becomes a surprise.`);
  }
  if (contract.cost?.style !== "free" && !(contract.cost?.estimateCents > 0)) {
    problems.push(`${id}: a paid connector must estimate its cost, or no ceiling can be enforced.`);
  }

  // Secrets belong to the platform or to a connected account — never typed
  // into a field an architect can read back out of a saved workflow.
  for (const field of contract.needs?.architect ?? []) {
    if (field.kind === "secret") {
      problems.push(`${id}: "${field.key}" is a secret asked of the architect. Secrets belong in platform needs.`);
    }
  }

  // A rule the engine has nowhere to look is a comment pretending to be a rule.
  //
  // This exact failure already happened here: four rules were declared, shown
  // to businesses on their setup form, and never read at run time — with a
  // comment above them claiming the engine enforced them. Refusing the
  // contract is what makes that impossible to repeat, because the connector
  // simply will not register.
  const rules = contract.rules ?? {};
  if (rules.requiresUnsubscribe && !rules.unsubscribeIn?.length) {
    problems.push(
      `${id}: it requires an unsubscribe but does not say which config key carries the message ("unsubscribeIn"), so nothing can check it.`
    );
  }
  if (rules.blockedCountries?.length && !rules.reaches?.length) {
    problems.push(
      `${id}: it blocks countries but does not say which config key holds the people it reaches ("reaches"), so nothing can check it.`
    );
  }
  for (const key of [...(rules.unsubscribeIn ?? []), ...(rules.reaches ?? [])]) {
    const known =
      (contract.needs?.business ?? []).some((field) => field.key === key) ||
      (contract.needs?.architect ?? []).some((field) => field.key === key) ||
      (contract.produces ?? []).some((output) => output.key === key);
    if (!known) {
      problems.push(
        `${id}: a rule points at "${key}", which this connector never asks for or produces. A rule aimed at nothing passes every time.`
      );
    }
  }

  return problems;
}

/** Every declared output key, for the engine's honesty check. */
export function requiredOutputKeys(contract: NodeFrame): string[] {
  return contract.produces.filter((output) => output.required).map((output) => output.key);
}

/**
 * Did the heart actually return what it promised?
 *
 * The whole point. A connector that reports success while returning nothing is
 * how a business ends up believing a customer was texted, or that three
 * appointment slots were real.
 */
export function checkHeartResult(
  contract: NodeFrame,
  result: HeartResult
): { ok: boolean; missing: string[] } {
  const missing = requiredOutputKeys(contract).filter((key) => {
    const value = result.outputs?.[key];
    if (value === undefined || value === null) return true;
    if (typeof value === "string" && value.trim() === "") return true;
    return false;
  });
  return { ok: missing.length === 0, missing };
}
