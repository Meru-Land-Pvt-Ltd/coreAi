/**
 * The rules that protect the person at the other end, and the platform.
 *
 * NOT the same as a business setting. A business may choose to call fewer
 * people; a business may not choose to call people who never agreed. These are
 * enforced by the engine — a heart cannot switch them off, and neither can an
 * architect.
 */
export type ConnectorRules = {
  /** A consent record must exist for this person before we reach them. */
  requiresConsent?: boolean;
  /** Every message must carry a working way out. */
  requiresUnsubscribe?: boolean;
  /** Countries this connector must refuse to operate on. */
  blockedCountries?: string[];
  /** The most this may do for one business in a day, whatever they set. */
  hardDailyCap?: number;
  /*
   * There used to be a `testOnlyToVerifiedIdentity` rule here.
   *
   * It is gone because it became redundant, not because it stopped mattering.
   * The engine now answers a rehearsal itself, from each output's declared
   * `sample`, and never calls the heart — so a test cannot reach a real person
   * whatever the connector does. A structural guarantee beats a rule that has
   * to be declared, and a rule that can never fire is exactly the thing this
   * file refuses to carry.
   */

  /**
   * Config keys whose text must contain a way out, when requiresUnsubscribe is set.
   *
   * A rule the engine cannot look at anywhere is not a rule, it is a comment.
   * These two fields are what turn the flags above into something checkable —
   * and `validateNodeFrame` REFUSES a contract that declares a rule without
   * saying where to check it. That is the part that matters: the previous
   * version of this file declared four rules the engine never read, with a
   * comment claiming they were enforced. Making the declaration impossible to
   * fake is a stronger fix than remembering to read it.
   */
  unsubscribeIn?: string[];

  /**
   * Config keys holding the people this connector will reach.
   *
   * Phone numbers or email addresses, as a single value or a list. Used by the
   * country block and by the rehearsal guard.
   */
  reaches?: string[];

  /** Anything else a maintainer must know, in plain words. */
  notes?: string[];
};

